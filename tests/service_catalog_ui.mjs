import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const root = new URL('../', import.meta.url);
const ctx = vm.createContext({formatPeso:n=>'PHP '+Number(n).toFixed(2),document:{getElementById:()=>null}});
const app = new vm.Script(fs.readFileSync(new URL('assets/js/customer/dashboard-booking.js', root),'utf8')+'; customerBookingMixin()').runInContext(ctx);
Object.assign(app, {selectedBranchForServices:'daraga', servicesCatalog:{daraga:Array.from({length:14},(_,i)=>({id:String(i),name:'Service '+i,category:i%2?'Hair':'Skin',price:499})), yashano:[{id:'Y1',name:'Facial',category:'Skin'}]},selectedServicesForBooking:[],bookingForm:{date:''},$nextTick:f=>f()});
assert.equal(app.pagedServices().length,6);
assert.equal(app.servicePageCount(),3);
app.changeServicePage(1);assert.equal(app.pagedServices()[0].id,'6');
app.toggleServiceSelection(app.pagedServices()[0]);
app.changeServicePage(1);assert.equal(app.pagedServices().length,2);
app.serviceSearch='service 6';app.servicePage=1;
assert.equal(app.getFilteredServices().length,1);
assert(app.isSelectedForBooking(app.getFilteredServices()[0]),'selection survives filters and pagination');
app.resetServiceFilters();app.serviceCategory='Skin';
assert.equal(app.getFilteredServices().length,7);
app.serviceSearch='SERVICE 12';assert.equal(app.getFilteredServices().length,1);
app.serviceSearch='no match';assert.equal(app.pagedServices().length,0);
app.selectedBranchForServices='yashano';app.resetServiceFilters();
assert.equal(app.pagedServices()[0].id,'Y1');
assert.equal(app.servicePage,1);
assert.equal(app.serviceReservationLabel({paymentRequirement:'50% Down Payment',reservationAmount:49,reservationLabel:'Full Payment'}),'PHP 49.00 (full payment)');
assert.equal(app.serviceReservationLabel({paymentRequirement:'50% Down Payment',reservationAmount:100,reservationLabel:'Minimum PHP100 Deposit'}),'PHP 100.00 (minimum deposit)');
assert.equal(app.serviceReservationLabel({paymentRequirement:'No Online Reservation'}),'No online payment required');
assert.equal(app.serviceReservationLabel({paymentRequirement:'50% Down Payment',reservationAmount:249.5,reservationLabel:'50% Down Payment'}),'PHP 249.50 (50%)');
console.log('PASS service search/category filters, paging, retained selection, branch reset, and payment preview labels.');
